/**
 * Generates client/src/data/function-names.ts from client/public/functions.json.
 *
 * The auto-linker needs every documented function name at runtime. Importing
 * the 1 MB functions.json into the bundle just for names would be wasteful,
 * so we derive a names-only module instead.
 *
 * Run:  npm run generate:link-data     (re-run whenever functions.json changes)
 *
 * It also applies FUNCTION_NAME_FIXES to both published copies of the dataset
 * (client/public/functions.json and scripts/processed-functions.json — the
 * deploy workflow ships the latter): two rows were scraped with broken names,
 * which made /function/... links resolve to pages titled "Uri functions" /
 * "AzureStorage. DataLake" (and would leave any prose mention of the real
 * names link-less). The fix is idempotent — it only fires while the old name
 * is still present.
 */
import { readFileSync, writeFileSync } from "node:fs";
import { dirname, resolve } from "node:path";
import { fileURLToPath } from "node:url";

const root = resolve(dirname(fileURLToPath(import.meta.url)), "..");
const datasetPaths = [
  resolve(root, "client/public/functions.json"),
  resolve(root, "scripts/processed-functions.json"),
];
const outPath = resolve(root, "client/src/data/function-names.ts");

/** Old name → correct name (content of the rows is untouched). */
const FUNCTION_NAME_FIXES = {
  "Uri functions": "Uri.BuildQueryString",
  "AzureStorage. DataLake": "AzureStorage.DataLake",
};

let functions = null;

for (const datasetPath of datasetPaths) {
  const rows = JSON.parse(readFileSync(datasetPath, "utf8"));

  let fixes = 0;
  for (const fn of rows) {
    const fixed = FUNCTION_NAME_FIXES[fn.name];
    if (fixed && !rows.some((f) => f.name === fixed)) {
      console.log(`fix (${datasetPath.split(/[\\/]/).slice(-1)[0]}): "${fn.name}" -> "${fixed}"`);
      fn.name = fixed;
      fixes++;
    }
  }

  if (fixes > 0) {
    writeFileSync(datasetPath, JSON.stringify(rows, null, 2), "utf8");
    console.log(`Applied ${fixes} name fix(es) to ${datasetPath}`);
  } else {
    console.log(`${datasetPath.split(/[\\/]/).slice(-1)[0]} names already correct`);
  }

  if (!functions) functions = rows;
}

const names = functions.map((f) => f.name);
const unique = [...new Set(names)];

const lines = unique
  .sort()
  .map((n) => `  ${JSON.stringify(n)},`)
  .join("\n");

const banner = `// AUTO-GENERATED by scripts/generate-link-data.mjs — do not edit by hand.
// Source: client/public/functions.json (${functions.length} rows, ${unique.length} unique names)

`;

writeFileSync(
  outPath,
  `${banner}export const functionNames: string[] = [\n${lines}\n];\n\n/** Fast membership test used by the auto-linker. */\nexport const functionNameSet = new Set<string>(functionNames);\n`,
  "utf8",
);

console.log(`Wrote ${unique.length} names to client/src/data/function-names.ts`);
